import java.util.Locale

enum class Lang { RU, EN }

/**
 * UI language. Source strings are Russian; [L] swaps in English and fills %1..%9.
 * The current language is snapshot state, so every composable re-renders when it changes.
 */
object I18n {
    var lang by mutableStateOf(systemLang())
    fun systemLang() = if (Locale.getDefault().language in setOf("ru", "uk", "be", "kk")) Lang.RU else Lang.EN
    val locale: Locale get() = if (lang == Lang.RU) Locale.forLanguageTag("ru") else Locale.ENGLISH
    fun apply(setting: String) { lang = when (setting) { "ru" -> Lang.RU; "en" -> Lang.EN; else -> systemLang() } }
}

fun L(ru: String, vararg args: Any?): String {
    var s = if (I18n.lang == Lang.EN) EN[ru] ?: ru else ru
    for (i in args.indices.reversed()) s = s.replace("%${i + 1}", args[i].toString())
    return s
}

