@file:OptIn(androidx.compose.material3.ExperimentalMaterial3ExpressiveApi::class)

package dev.uplinx

import androidx.compose.material3.MaterialShapes
import androidx.graphics.shapes.RoundedPolygon
import java.io.File

/**
 * Exports the Material 3 Expressive shapes as SVG path data (viewbox 0..100) for the Rust/Slint port,
 * so both versions draw exactly the same outlines.
 */
object ShapeExport {
    private fun svg(p: RoundedPolygon): String {
        val sb = StringBuilder()
        fun f(v: Float) = "%.2f".format(java.util.Locale.ROOT, v * 100f)
        p.cubics.forEachIndexed { i, c ->
            if (i == 0) sb.append("M ${f(c.anchor0X)} ${f(c.anchor0Y)} ")
            sb.append("C ${f(c.control0X)} ${f(c.control0Y)} ${f(c.control1X)} ${f(c.control1Y)} ${f(c.anchor1X)} ${f(c.anchor1Y)} ")
        }
        return sb.append("Z").toString()
    }

    @JvmStatic fun main(args: Array<String>) {
        val shapes = mapOf(
            "circle" to MaterialShapes.Circle, "cookie4" to MaterialShapes.Cookie4Sided, "cookie6" to MaterialShapes.Cookie6Sided,
            "cookie9" to MaterialShapes.Cookie9Sided, "cookie12" to MaterialShapes.Cookie12Sided, "clover4" to MaterialShapes.Clover4Leaf,
            "clover8" to MaterialShapes.Clover8Leaf, "soft-burst" to MaterialShapes.SoftBurst, "sunny" to MaterialShapes.Sunny,
            "flower" to MaterialShapes.Flower, "pill" to MaterialShapes.Pill, "gem" to MaterialShapes.Gem, "pentagon" to MaterialShapes.Pentagon,
            "puffy" to MaterialShapes.Puffy, "burst" to MaterialShapes.Burst, "soft-boom" to MaterialShapes.SoftBoom,
        )
        val out = File(args.firstOrNull() ?: "uplinx-rs/ui/shapes.slint")
        out.parentFile.mkdirs()
        out.writeText(buildString {
            appendLine("// Generated by `gradlew shapeExport` from androidx MaterialShapes — do not edit.")
            appendLine("export global Shapes {")
            shapes.forEach { (name, p) -> appendLine("    out property <string> $name: \"${svg(p)}\";") }
            appendLine("}")
        })
        println("shapes written to ${out.absolutePath}")
        System.exit(0)
    }
}
